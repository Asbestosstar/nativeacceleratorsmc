#!/usr/bin/env bash
# Create a disposable, deterministic Fabric-server test instance. Does not modify the source server.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
SOURCE_SERVER=${NATIVESERVER0_DIR:-"$HOME/Downloads/nativeserver0"}
BENCH_ROOT=${NATIVESERVER0_BENCH_ROOT:-"$ROOT/target/nativeserver0-benchmark"}
SEED=${NATIVESERVER0_SEED:-"-4630982771278649347"}
INSTANCE_NAME=${1:-native}
INSTANCE="$BENCH_ROOT/$INSTANCE_NAME"

case "$INSTANCE_NAME" in
  baseline|native) ;;
  *) echo "Usage: $0 [baseline|native]" >&2; exit 64 ;;
esac

for required in server.jar fabric-server-launch.jar libraries; do
  if [[ ! -e "$SOURCE_SERVER/$required" ]]; then
    echo "Missing $SOURCE_SERVER/$required; set NATIVESERVER0_DIR to the supplied server directory." >&2
    exit 66
  fi
done

rm -rf "$INSTANCE"
mkdir -p "$INSTANCE"
cp "$SOURCE_SERVER/server.jar" "$SOURCE_SERVER/fabric-server-launch.jar" "$INSTANCE/"
cp -R "$SOURCE_SERVER/libraries" "$INSTANCE/libraries"
printf 'eula=true\n' > "$INSTANCE/eula.txt"
cat > "$INSTANCE/server.properties" <<EOF
# Generated by scripts/setup-nativeserver0-benchmark.sh; do not edit for comparable runs.
level-name=benchmark-world
level-seed=$SEED
gamemode=creative
difficulty=normal
hardcore=false
allow-cheats=true
online-mode=false
server-ip=
server-port=25565
max-players=1
view-distance=10
simulation-distance=10
spawn-protection=0
white-list=false
enforce-whitelist=false
pvp=false
enable-command-block=true
allow-flight=true
network-compression-threshold=256
sync-chunk-writes=true
max-tick-time=-1
enable-rcon=false
enable-query=false
motd=Native Accelerator reproducible benchmark
EOF

if [[ "$INSTANCE_NAME" == native ]]; then
  MOD_JAR=${NATIVESERVER0_MOD_JAR:-"$ROOT/target/native-accelerator-0.1.0-SNAPSHOT.jar"}
  if [[ ! -f "$MOD_JAR" ]]; then
    echo "Missing built mod JAR: $MOD_JAR. Build/package the project first or set NATIVESERVER0_MOD_JAR." >&2
    exit 66
  fi
  mkdir -p "$INSTANCE/mods"
  cp "$MOD_JAR" "$INSTANCE/mods/native-accelerator.jar"
fi

printf 'Prepared %s\n  source: %s\n  instance: %s\n  seed: %s\n' "$INSTANCE_NAME" "$SOURCE_SERVER" "$INSTANCE" "$SEED"
